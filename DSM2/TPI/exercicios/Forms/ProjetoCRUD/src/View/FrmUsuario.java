    private void jtbTabelaUsuarioMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtbTabelaUsuarioMouseClicked
        // TODO add your handling code here:
        //para pegar o numero da linha selecionada na tabela
        int linhaSelecionada = jtbTabelaUsuario.getSelectedRow();

        //mostra as informações da linha selecionada na tabela na caixa de texto
        txtCodigo.setText(jtbTabelaUsuario.getValueAt(linhaSelecionada, 0).toString());
        txtLogin.setText(jtbTabelaUsuario.getValueAt(linhaSelecionada, 1).toString());
        txtSenha.setText(jtbTabelaUsuario.getValueAt(linhaSelecionada, 2).toString());
        txtTelefone.setText(jtbTabelaUsuario.getValueAt(linhaSelecionada, 3).toString());

    }//GEN-LAST:event_jtbTabelaUsuarioMouseClicked

