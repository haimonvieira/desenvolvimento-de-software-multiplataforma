    public void consultar() {

        ResultSet tabela;
        tabela = null;

        //CHAMAR O MÉTODO CONSULTAR
        tabela = usu.consultar();

        DefaultTableModel modelo = (DefaultTableModel) jtbTabelaUsuario.getModel();
        modelo.setNumRows(0);

        try {
            while (tabela.next()) {
                modelo.addRow(new String[]{tabela.getString(2),
                    tabela.getString(3), tabela.getString(4),
                    tabela.getString(5)});
            }
        } catch (SQLException erro) {
            JOptionPane.showMessageDialog(null, "Erro preencher tabela" + erro);
        }

    }

